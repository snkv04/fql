"""Generate and submit Slurm scripts for a hyperparameter sweep of main.py.

One script is written to slurm_scripts/generated/hyperparameter_sweep/ for each (environment, alpha, discount, seed) in
the cartesian product. Each (environment, alpha, discount) gets its own run group,
<run_group_prefix>_<env>_a<alpha>_g<discount>, so that its seeds are grouped together on disk (exp/fql/<run_group>/)
and in W&B.

Example:
    python submit_train_sweep.py --dry_run
"""

import itertools
import os
import subprocess

from absl import app, flags, logging

FLAGS = flags.FLAGS

flags.DEFINE_list(
    'envs',
    [
        'antmaze-medium-navigate-singletask-v0',
        'antmaze-medium-explore-singletask-v0',
        'cube-double-play-singletask-v0',
        'cube-double-noisy-singletask-v0',
    ],
    'Environment (dataset) names.',
)
flags.DEFINE_list(
    'alphas', ['3', '10', '30', '100', '300', '1000', '3000', '10000'], 'BC coefficients (--agent.alpha).'
)
flags.DEFINE_list('discounts', ['0.99', '0.995'], 'Discount factors (--agent.discount).')
flags.DEFINE_list('seeds', ['0'], 'Training seeds.')
flags.DEFINE_string('agent', 'agents/fql_plan.py', 'Agent config file (--agent).')
flags.DEFINE_integer('offline_steps', 1000000, 'Number of offline steps.')
flags.DEFINE_integer('online_steps', 1000000, 'Number of online steps (0: offline RL only).')
flags.DEFINE_string('run_group_prefix', 'sweep', 'Prefix of the run groups.')
flags.DEFINE_string(
    'extra_flags', '', 'Additional flags passed to main.py in every job (e.g., "--eval_interval=200000").'
)
flags.DEFINE_bool('dry_run', False, 'Whether to only write the scripts without submitting them with sbatch.')

REPO_DIR = os.path.dirname(os.path.abspath(__file__))

SCRIPT_TEMPLATE = """#!/bin/bash

#SBATCH --output={repo_dir}/slurm_logs/%x_%j.out
#SBATCH --error={repo_dir}/slurm_logs/%x_%j.err

#SBATCH --time=48:00:00
#SBATCH --mem=32G
#SBATCH --partition=gpus
#SBATCH --gres=gpu:1
#SBATCH --cpus-per-task=4

# Print Slurm job info
echo "===== Slurm job info ====="
echo "Job: ${{SLURM_JOB_NAME}} (${{SLURM_JOB_ID}})"
echo "Node(s): ${{SLURM_JOB_NODELIST}} (running on $(hostname))"
echo "Started: $(date)"
echo "SBATCH directives:"
grep '^#SBATCH' "$0" | sed 's/^#SBATCH /    /'
echo "CUDA_VISIBLE_DEVICES: ${{CUDA_VISIBLE_DEVICES:-<unset>}}"
nvidia-smi -L 2>/dev/null
echo "=========================="

export MUJOCO_GL=osmesa  # To enable headless rendering

# Hyperparameter sweep (generated by submit_train_sweep.py).
cd {repo_dir}/
source .venv/bin/activate
unset LD_LIBRARY_PATH  # use .venv's own CUDA libs, not text-planning's from ~/.bashrc
export LD_LIBRARY_PATH=$HOME/.mujoco/mujoco210/bin  # MuJoCo 2.1.0 for mujoco_py (needed by D4RL)
export MUJOCO_PY_FORCE_CPU=1  # Use mujoco_py's CPU build on GPU nodes (only D4RL physics needs it; no rendering)
export TMPDIR=/cs/data/people/svangaru/tmp  # Node-local /ltmp can be full
mkdir -p "$TMPDIR"
python main.py \\
    --agent={agent} \\
    --env_name={env_name} \\
    --offline_steps={offline_steps} \\
    --online_steps={online_steps} \\
    --agent.alpha={alpha} \\
    --agent.discount={discount} \\
    --run_group={run_group} \\
    --seed={seed}{extra_flags}
"""


def get_env_tag(env_name):
    """Return a short name of the environment for run groups and script names (e.g., cube-double-play)."""
    return env_name.replace('-singletask', '').removesuffix('-v0')


def main(_):
    for value in FLAGS.alphas + FLAGS.discounts:
        float(value)  # Check that the hyperparameters are numbers.

    agent_name = os.path.splitext(os.path.basename(FLAGS.agent))[0]
    script_dir = os.path.join(REPO_DIR, 'slurm_scripts', 'generated', 'hyperparameter_sweep')
    os.makedirs(script_dir, exist_ok=True)
    if not FLAGS.dry_run:
        os.makedirs(os.path.join(REPO_DIR, 'slurm_logs'), exist_ok=True)

    extra_flags = ''.join(f' \\\n    {flag}' for flag in FLAGS.extra_flags.split())
    jobs = list(itertools.product(FLAGS.envs, FLAGS.alphas, FLAGS.discounts, FLAGS.seeds))
    for env_name, alpha, discount, seed in jobs:
        env_tag = get_env_tag(env_name)
        run_group = f'{FLAGS.run_group_prefix}_{env_tag}_a{alpha}_g{discount}'
        script_path = os.path.join(script_dir, f'train_{agent_name}_{env_tag}_a{alpha}_g{discount}_sd{seed}.sh')
        if os.path.exists(script_path):
            logging.warning('Overwriting existing script %s.', script_path)

        script = SCRIPT_TEMPLATE.format(
            repo_dir=REPO_DIR,
            agent=FLAGS.agent,
            env_name=env_name,
            offline_steps=FLAGS.offline_steps,
            online_steps=FLAGS.online_steps,
            alpha=alpha,
            discount=discount,
            run_group=run_group,
            seed=seed,
            extra_flags=extra_flags,
        )
        with open(script_path, 'w') as f:
            f.write(script)
        os.chmod(script_path, 0o755)

        if FLAGS.dry_run:
            print(f'[dry run] {script_path}')
        else:
            result = subprocess.run(['sbatch', script_path], check=True, capture_output=True, text=True)
            print(f'{result.stdout.strip()} ({script_path})')

    print(f'{len(jobs)} jobs ({"written" if FLAGS.dry_run else "submitted"}).')


if __name__ == '__main__':
    app.run(main)
