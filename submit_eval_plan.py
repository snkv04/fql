"""Generate and submit Slurm scripts for test-time planning evaluation (eval_plan.py) of FQL-plan runs (e.g., seeds).

One script is written to slurm_scripts/generated/ for each (plan_horizon, plan_samples) pair in the cartesian product,
and each job evaluates all of the training runs with its pair. Each job writes the results of all training runs to
<first run_dir>/eval_plan/H<horizon>_N<samples>.csv, so that concurrent jobs do not overwrite each other's results.
Jobs are assigned to the nodes in JOBS_PER_NODE in order, with at most the node's limit of jobs on each node.
"""

import glob
import itertools
import json
import os
import subprocess

from absl import app, flags, logging

FLAGS = flags.FLAGS

flags.DEFINE_list('run_dirs', None, 'Training run directories (each containing flags.json and params_*.pkl).')
flags.DEFINE_list('plan_horizons', None, 'Planning horizons H to evaluate.')
flags.DEFINE_list('plan_samples', None, 'Numbers of candidates N to evaluate.')
flags.DEFINE_bool('dry_run', False, 'Whether to only write the scripts without submitting them with sbatch.')

flags.mark_flags_as_required(['run_dirs', 'plan_horizons', 'plan_samples'])

REPO_DIR = os.path.dirname(os.path.abspath(__file__))
SCRIPT_DIR = os.path.join(REPO_DIR, 'slurm_scripts', 'generated')

# Maximum number of jobs per node, in the order that nodes are filled (each job uses 1 GPU, 4 CPUs, and 64G of memory).
JOBS_PER_NODE = {
    'gpu1601': 3,
    'gpu1602': 3,
    'gpu1603': 3,
    'gpu1604': 3,
    'gpu1605': 3,
}

SCRIPT_TEMPLATE = """#!/bin/bash

#SBATCH --output={repo_dir}/slurm_logs/%x_%j.out
#SBATCH --error={repo_dir}/slurm_logs/%x_%j.err

#SBATCH --partition=gpus
#SBATCH --nodelist={node}
#SBATCH --gres=gpu:1
#SBATCH --cpus-per-task=4
#SBATCH --time=48:00:00
#SBATCH --mem=64G

# Print Slurm job info
echo "===== Slurm job info ====="
echo "Job: ${{SLURM_JOB_NAME}} (${{SLURM_JOB_ID}})"
echo "Node(s): ${{SLURM_JOB_NODELIST}} (running on $(hostname))"
echo "Started: $(date)"
echo "SBATCH directives:"
grep '^#SBATCH' "$0" | sed 's/^#SBATCH /    /'
echo "CUDA_VISIBLE_DEVICES: ${{CUDA_VISIBLE_DEVICES:-<unset>}}"
nvidia-smi -L 2>/dev/null
echo "=========================="

export MUJOCO_GL=osmesa  # To enable headless rendering

# Test-time planning evaluation of saved FQL-plan checkpoints (generated by submit_eval_plan.py; see eval_plan.py).
# Checkpoints already in the output CSV with this setting are skipped.
cd {repo_dir}/
source .venv/bin/activate
unset LD_LIBRARY_PATH  # use .venv's own CUDA libs, not text-planning's from ~/.bashrc
export LD_LIBRARY_PATH=$HOME/.mujoco/mujoco210/bin  # MuJoCo 2.1.0 for mujoco_py (needed by D4RL)
export MUJOCO_PY_FORCE_CPU=1  # Use mujoco_py's CPU build on GPU nodes (only D4RL physics needs it; no rendering)
export TMPDIR=/cs/data/people/svangaru/tmp  # Node-local /ltmp can be full
mkdir -p "$TMPDIR"
python eval_plan.py \\
    --run_dirs={run_dirs} \\
    --plan_horizon={horizon} \\
    --plan_samples={num_samples} \\
    --output={output}
"""


def check_run_dir(run_dir):
    """Check that the run directory is an fql_plan run with saved checkpoints, and return its run group."""
    flags_path = os.path.join(run_dir, 'flags.json')
    assert os.path.exists(flags_path), f'No flags.json in {run_dir}.'
    with open(flags_path) as f:
        train_flags = json.load(f)
    agent_name = train_flags['agent']['agent_name']
    assert agent_name == 'fql_plan', f'Expected an fql_plan run, got {agent_name}.'
    assert glob.glob(os.path.join(run_dir, 'params_*.pkl')), f'No checkpoints (params_*.pkl) in {run_dir}.'
    return train_flags['run_group']


def get_settings(horizons, samples):
    """Return the sorted (plan_horizon, plan_samples) settings, warning about ones that duplicate others' actions."""
    settings = list(itertools.product(sorted(set(horizons)), sorted(set(samples))))
    for horizon, num_samples in settings:
        if horizon == 0 and num_samples > 1:
            logging.warning('H=0, N=%d executes the same actions as H=0, N=1 (no planning).', num_samples)
        elif horizon > 0 and num_samples == 1:
            logging.warning('H=%d, N=1 executes the same first action as H=0 (only one candidate).', horizon)
    return settings


def main(_):
    run_dirs = [os.path.abspath(run_dir) for run_dir in FLAGS.run_dirs]
    run_groups = {check_run_dir(run_dir) for run_dir in run_dirs}
    if len(run_dirs) == 1:
        run_name = os.path.basename(os.path.normpath(run_dirs[0]))
    else:
        # Name the scripts after the run group of the training runs (e.g., seeds).
        assert len(run_groups) == 1, f'The training runs have different run groups: {sorted(run_groups)}.'
        run_name = run_groups.pop()

    settings = get_settings([int(h) for h in FLAGS.plan_horizons], [int(n) for n in FLAGS.plan_samples])
    # One slot per job that a node can run, filling each node up to its limit before moving on to the next.
    slots = [node for node, limit in JOBS_PER_NODE.items() for _ in range(limit)]
    assert slots, 'JOBS_PER_NODE has no job slots.'
    if len(settings) > len(slots):
        logging.warning(
            '%d jobs exceed the capacity of %d jobs (%s); cycling through the nodes again.',
            len(settings),
            len(slots),
            ', '.join(f'{node}: {limit}' for node, limit in JOBS_PER_NODE.items()),
        )

    os.makedirs(SCRIPT_DIR, exist_ok=True)
    if not FLAGS.dry_run:
        os.makedirs(os.path.join(REPO_DIR, 'slurm_logs'), exist_ok=True)

    for j, (horizon, num_samples) in enumerate(settings):
        node = slots[j % len(slots)]
        setting_name = f'H{horizon}_N{num_samples}'
        script_path = os.path.join(SCRIPT_DIR, f'eval_plan_{run_name}_{setting_name}.sh')
        if os.path.exists(script_path):
            logging.warning('Overwriting existing script %s.', script_path)

        script = SCRIPT_TEMPLATE.format(
            repo_dir=REPO_DIR,
            node=node,
            run_dirs=','.join(run_dirs),
            horizon=horizon,
            num_samples=num_samples,
            output=os.path.join('eval_plan', f'{setting_name}.csv'),
        )
        with open(script_path, 'w') as f:
            f.write(script)
        os.chmod(script_path, 0o755)

        if FLAGS.dry_run:
            print(f'[dry run] {setting_name} on {node}: {script_path}')
        else:
            result = subprocess.run(['sbatch', script_path], check=True, capture_output=True, text=True)
            print(f'{setting_name} on {node}: {result.stdout.strip()} ({script_path})')


if __name__ == '__main__':
    app.run(main)
