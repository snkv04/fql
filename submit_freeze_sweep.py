"""Generate and submit Slurm scripts for the network-freezing ablation of fql_plan (offline-to-online RL).

For each (configuration, freeze arm, seed) in the cartesian product, one script is written to
slurm_scripts/generated/freeze_sweep/. Each job trains fql_plan from scratch (offline_steps offline + online_steps
online) and freezes the arm's networks only during online fine-tuning (--agent.freeze_*_online), so that all networks
are still learned offline. Online data are collected and evaluations are run with the planner (H=plan_horizon,
N=plan_samples), so that the dynamics model affects the actions.

Each (configuration, arm) gets its own run group, <run_group_prefix>_<env>[_<tag>]_<arm>, so that its seeds are grouped
together on disk (exp/fql/<run_group>/) and in W&B.

Example:
    python submit_freeze_sweep.py --dry_run
"""

import itertools
import os
import subprocess

from absl import app, flags, logging

FLAGS = flags.FLAGS

flags.DEFINE_list('seeds', ['0'], 'Training seeds.')
flags.DEFINE_string('agent', 'agents/fql_plan.py', 'Agent config file (--agent).')
flags.DEFINE_integer('offline_steps', 1000000, 'Number of offline steps.')
flags.DEFINE_integer('online_steps', 1000000, 'Number of online steps.')
flags.DEFINE_integer('plan_horizon', 10, 'Planning horizon H for online data collection and evaluation.')
flags.DEFINE_integer('plan_samples', 32, 'Number of planning candidates N for online data collection and evaluation.')
flags.DEFINE_string('run_group_prefix', 'freeze', 'Prefix of the run groups.')
flags.DEFINE_string(
    'extra_flags', '', 'Additional flags passed to main.py in every job (e.g., "--eval_interval=200000").'
)
flags.DEFINE_bool('dry_run', False, 'Whether to only write the scripts without submitting them with sbatch.')

REPO_DIR = os.path.dirname(os.path.abspath(__file__))
SCRIPT_DIR = os.path.join(REPO_DIR, 'slurm_scripts', 'generated', 'freeze_sweep')

# (environment, alpha, discount, tag). The tag is a short description of the configuration used in the run group
# instead of alpha and discount (None: no tag; the environment must then appear only once).
CONFIGS = [
    ('antmaze-medium-navigate-singletask-v0', '300', '0.995', 'both-stages-matter'),
    ('antmaze-medium-navigate-singletask-v0', '10', '0.99', 'learned-mostly-OFFline'),
    ('antmaze-medium-explore-singletask-v0', '3', '0.995', 'learned-mostly-OFFline'),
    ('antmaze-medium-explore-singletask-v0', '3', '0.99', 'both-stages-matter'),
    ('cube-double-play-singletask-v0', '1000', '0.99', None),
    ('cube-double-noisy-singletask-v0', '30', '0.99', 'learned-mostly-ONline'),
    ('cube-double-noisy-singletask-v0', '10', '0.99', 'both-stages-matter'),
]

# Freeze arm name -> networks frozen during online fine-tuning (--agent.freeze_<network>_online=True).
ARMS = {
    'none': [],
    'fql': ['bc', 'actor', 'critic'],
    'dyn': ['dynamics'],
    'bc': ['bc'],
    'bc+dyn': ['bc', 'dynamics'],
    'critic': ['critic'],
}

SCRIPT_TEMPLATE = """#!/bin/bash

#SBATCH --output={repo_dir}/slurm_logs/%x_%j.out
#SBATCH --error={repo_dir}/slurm_logs/%x_%j.err

#SBATCH --time=48:00:00
#SBATCH --mem=32G
#SBATCH --partition=gpus
#SBATCH --gres=gpu:1
#SBATCH --cpus-per-task=4

# Print Slurm job info
echo "===== Slurm job info ====="
echo "Job: ${{SLURM_JOB_NAME}} (${{SLURM_JOB_ID}})"
echo "Node(s): ${{SLURM_JOB_NODELIST}} (running on $(hostname))"
echo "Started: $(date)"
echo "SBATCH directives:"
grep '^#SBATCH' "$0" | sed 's/^#SBATCH /    /'
echo "CUDA_VISIBLE_DEVICES: ${{CUDA_VISIBLE_DEVICES:-<unset>}}"
nvidia-smi -L 2>/dev/null
echo "=========================="

export MUJOCO_GL=osmesa  # To enable headless rendering

# Network-freezing ablation (generated by submit_freeze_sweep.py).
cd {repo_dir}/
source .venv/bin/activate
unset LD_LIBRARY_PATH  # use .venv's own CUDA libs, not text-planning's from ~/.bashrc
export LD_LIBRARY_PATH=$HOME/.mujoco/mujoco210/bin  # MuJoCo 2.1.0 for mujoco_py (needed by D4RL)
export MUJOCO_PY_FORCE_CPU=1  # Use mujoco_py's CPU build on GPU nodes (only D4RL physics needs it; no rendering)
export TMPDIR=/cs/data/people/svangaru/tmp  # Node-local /ltmp can be full
mkdir -p "$TMPDIR"
python main.py \\
    --agent={agent} \\
    --env_name={env_name} \\
    --offline_steps={offline_steps} \\
    --online_steps={online_steps} \\
    --agent.alpha={alpha} \\
    --agent.discount={discount} \\
    --agent.plan_horizon={plan_horizon} \\
    --agent.plan_samples={plan_samples} \\
    --collect_with_planner \\
    --eval_with_planner \\
    --run_group={run_group} \\
    --seed={seed}{freeze_flags}{extra_flags}
"""


def get_env_tag(env_name):
    """Return a short name of the environment for run groups and script names (e.g., cube-double-play)."""
    return env_name.replace('-singletask', '').removesuffix('-v0')


def get_config_name(env_name, tag):
    """Return the configuration's name for run groups and script names (e.g., cube-double-noisy_both-stages-matter)."""
    return get_env_tag(env_name) + (f'_{tag}' if tag else '')


def main(_):
    assert FLAGS.online_steps > 0, 'Freezing only applies to online fine-tuning (--online_steps must be positive).'
    config_names = [get_config_name(env_name, tag) for env_name, _, _, tag in CONFIGS]
    assert len(set(config_names)) == len(config_names), f'Configuration names must be unique: {config_names}'
    for _, alpha, discount, _ in CONFIGS:
        float(alpha), float(discount)  # Check that the hyperparameters are numbers.

    agent_name = os.path.splitext(os.path.basename(FLAGS.agent))[0]
    os.makedirs(SCRIPT_DIR, exist_ok=True)
    if not FLAGS.dry_run:
        os.makedirs(os.path.join(REPO_DIR, 'slurm_logs'), exist_ok=True)

    extra_flags = ''.join(f' \\\n    {flag}' for flag in FLAGS.extra_flags.split())
    jobs = list(itertools.product(CONFIGS, ARMS.items(), FLAGS.seeds))
    for (env_name, alpha, discount, tag), (arm_name, frozen), seed in jobs:
        config_name = get_config_name(env_name, tag)
        run_group = f'{FLAGS.run_group_prefix}_{config_name}_{arm_name}'
        script_path = os.path.join(SCRIPT_DIR, f'train_{agent_name}_{config_name}_{arm_name}_sd{seed}.sh')
        if os.path.exists(script_path):
            logging.warning('Overwriting existing script %s.', script_path)

        freeze_flags = ''.join(f' \\\n    --agent.freeze_{network}_online=True' for network in frozen)
        script = SCRIPT_TEMPLATE.format(
            repo_dir=REPO_DIR,
            agent=FLAGS.agent,
            env_name=env_name,
            offline_steps=FLAGS.offline_steps,
            online_steps=FLAGS.online_steps,
            alpha=alpha,
            discount=discount,
            plan_horizon=FLAGS.plan_horizon,
            plan_samples=FLAGS.plan_samples,
            run_group=run_group,
            seed=seed,
            freeze_flags=freeze_flags,
            extra_flags=extra_flags,
        )
        with open(script_path, 'w') as f:
            f.write(script)
        os.chmod(script_path, 0o755)

        if FLAGS.dry_run:
            print(f'[dry run] {script_path}')
        else:
            result = subprocess.run(['sbatch', script_path], check=True, capture_output=True, text=True)
            print(f'{result.stdout.strip()} ({script_path})')

    print(f'{len(jobs)} jobs ({"written" if FLAGS.dry_run else "submitted"}).')


if __name__ == '__main__':
    app.run(main)
